function makeContacts(index, city, options) {
  const std = STD_BY_CITY[city] || '0120';
  const suffix = String(index).padStart(2, '0');
  const verified =
    options.verifiedDaysAgo === undefined || options.verifiedDaysAgo === null
      ? null
      : daysAgo(options.verifiedDaysAgo);

  return {
    reception: {
      phone: `${std}-00000${suffix}`,
      alternatePhone: `${std}-00003${suffix}`,
      receptionistName: RECEPTION_NAMES[index % RECEPTION_NAMES.length],
      whatsapp: `90001${String(index).padStart(5, '0')}`,
      is24x7: options.reception24x7 ?? true,
      timings: { open: options.open || '09:00', close: options.close || '21:00' },
    },
    emergencyWard: { phone: `${std}-00001${suffix}` },
    ambulance: { phone: options.hasAmbulance === false ? '' : `90000${String(index).padStart(5, '0')}` },
    mainLine: { phone: `${std}-00002${suffix}` },
    lastVerified: verified,
  };
}


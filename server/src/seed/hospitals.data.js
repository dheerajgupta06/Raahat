export function buildSeedHospitals() {
  return HOSPITALS.map((entry, index) => {
    const indexFromOne = index + 1;
    const contacts = makeContacts(indexFromOne, entry.city, {
      verifiedDaysAgo: entry.verifiedDaysAgo,
      reception24x7: entry.reception24x7,
      open: entry.open,
      close: entry.close,
      hasAmbulance: entry.ambulanceAvailable,
    });

    const beds = BED_KEYS.reduce((acc, key) => {
      acc[key] = entry.beds[key] || bed(0, 0);
      return acc;
    }, {});

    return {
      name: entry.name,
      type: entry.type,
      address: entry.address,
      city: entry.city,
      state: entry.state,
      pincode: entry.pincode,
      location: { type: 'Point', coordinates: entry.coords },
      is24x7: entry.is24x7 ?? true,
      ambulanceAvailable: entry.ambulanceAvailable ?? true,
      specialties: entry.specialties,
      contacts,
      beds,
      oxygenStatus: entry.oxygenStatus,
      oxygenCylinders: entry.oxygenCylinders,
      doctorsOnDuty: entry.doctors,
      lastUpdated: minutesAgo(entry.updatedMinutesAgo),
      isDemo: true,
      adminId: null,
    };
  });
}


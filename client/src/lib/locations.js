const R_KM = 6371;
const rad = (value) => (value * Math.PI) / 180;

export function distanceKm(lat1, lng1, lat2, lng2) {
  const dLat = rad(lat2 - lat1);
  const dLng = rad(lng2 - lng1);
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(rad(lat1)) * Math.cos(rad(lat2)) * Math.sin(dLng / 2) ** 2;
  return 2 * R_KM * Math.asin(Math.min(1, Math.sqrt(a)));
}

export function findNearestLocality(lat, lng) {
  let best = null;
  for (const locality of LOCALITIES) {
    const d = distanceKm(lat, lng, locality.lat, locality.lng);
    if (!best || d < best.distanceKm) best = { ...locality, distanceKm: d };
  }
  return best;
}

export function describeCoordinates(lat, lng) {
  const nearest = findNearestLocality(lat, lng);
  if (nearest && nearest.distanceKm <= 15) {
    return { label: nearest.name, city: nearest.city, nearest };
  }
  return { label: 'Your location', city: nearest?.city || '', nearest };
}

export function searchLocalities(query, limit = 8) {
  const value = String(query || '').trim().toLowerCase();
  if (!value) return LOCALITIES.slice(0, limit);
  return LOCALITIES.filter((locality) => {
    const haystack = `${locality.name} ${locality.city} ${locality.state}`.toLowerCase();
    return haystack.includes(value);
  }).slice(0, limit);
}
